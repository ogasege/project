// Generates src/lib/integration-logos.ts: the real brand mark for each catalog app.
// Sources, in order: Iconify "logos" (SVG Logos, CC0, full colour), then Simple Icons (CC0,
// single path in the brand's colour). Apps neither set covers fall back to a monogram in the UI.
//
//   node scripts/gen-integration-logos.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalogSrc = fs.readFileSync(path.join(root, "src/lib/integrations-catalog.ts"), "utf8");
const apps = [...catalogSrc.matchAll(/app\("([a-z0-9-]+)", "([^"]+)"/g)].map((m) => ({ id: m[1], name: m[2] }));

const logos = JSON.parse(fs.readFileSync(path.join(root, "node_modules/@iconify-json/logos/icons.json"), "utf8"));
const simple = JSON.parse(fs.readFileSync(path.join(root, "node_modules/simple-icons/data/simple-icons.json"), "utf8"));
const simpleList = Array.isArray(simple) ? simple : simple.icons;
const simpleSvgDir = path.join(root, "node_modules/simple-icons/icons");

// Explicit picks where the default name guess is wrong or a better mark exists.
const LOGOS_OVERRIDES = {
  github: "github-icon",
  "github-copilot": "github-copilot",
  claude: "claude-icon",
  chatgpt: "openai-icon",
  "microsoft-teams": "microsoft-teams",
  onedrive: "microsoft-onedrive",
  monday: "monday-icon",
  front: "frontapp",
  "incident-io": "incident-icon",
  "google-workspace": "google-icon",
  x: "x",
  "entra-id": "microsoft-azure",
};
const SKIP = new Set(["savants-mcp", "webhook", "email-intake"]); // rendered with product glyphs

const slugify = (t) => t.toLowerCase().replace(/\+/g, "plus").replace(/\./g, "dot").replace(/&/g, "and").replace(/[^a-z0-9]/g, "");

function resolveLogos(name) {
  if (logos.icons[name]) return logos.icons[name];
  const alias = logos.aliases?.[name];
  if (alias) return logos.icons[alias.parent];
  return null;
}

// Prefix every id in an icon body so several inline SVGs on one page never share gradient ids.
function scopeIds(body, prefix) {
  const ids = [...body.matchAll(/id="([^"]+)"/g)].map((m) => m[1]);
  let out = body;
  for (const id of ids) {
    const esc = id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    out = out
      .replace(new RegExp(`id="${esc}"`, "g"), `id="${prefix}-${id}"`)
      .replace(new RegExp(`url\\(#${esc}\\)`, "g"), `url(#${prefix}-${id})`)
      .replace(new RegExp(`href="#${esc}"`, "g"), `href="#${prefix}-${id}"`);
  }
  return out;
}

const result = {};
const missing = [];
for (const app of apps) {
  if (SKIP.has(app.id)) continue;
  const candidates = [LOGOS_OVERRIDES[app.id], `${app.id}-icon`, app.id, `${slugify(app.name)}-icon`, slugify(app.name)].filter(Boolean);
  let found = null;
  for (const c of candidates) {
    const icon = resolveLogos(c);
    if (icon) {
      found = { source: "logos", name: c, body: scopeIds(icon.body, `lg-${app.id}`), width: icon.width ?? logos.width ?? 256, height: icon.height ?? logos.height ?? 256 };
      break;
    }
  }
  if (!found) {
    const slugs = [app.id.replace(/-/g, ""), slugify(app.name)];
    const hit = simpleList.find((i) => slugs.includes(i.slug ?? slugify(i.title)));
    if (hit) {
      const slug = hit.slug ?? slugify(hit.title);
      const svg = fs.readFileSync(path.join(simpleSvgDir, `${slug}.svg`), "utf8");
      const d = svg.match(/<path d="([^"]+)"/)?.[1];
      if (d) found = { source: "simple-icons", name: slug, body: `<path fill="#${hit.hex}" d="${d}"/>`, width: 24, height: 24 };
    }
  }
  if (found) result[app.id] = found;
  else missing.push(app.name);
}

const header = `// GENERATED by scripts/gen-integration-logos.mjs. Do not edit by hand.
// Brand marks from Iconify "logos" (SVG Logos, CC0) and Simple Icons (CC0). Trademarks belong to
// their owners and are used only to identify each integration.
// No open logo found for: ${missing.join(", ") || "none"}.
`;
const body = `export interface BrandLogo { source: "logos" | "simple-icons"; name: string; body: string; width: number; height: number }

export const INTEGRATION_LOGOS: Record<string, BrandLogo> = ${JSON.stringify(result, null, 0).replace(/},"/g, '},\n  "')};
`;
fs.writeFileSync(path.join(root, "src/lib/integration-logos.ts"), header + body);
console.log(`logos: ${Object.keys(result).length} apps; missing: ${missing.length} (${missing.join(", ")})`);
